import { WeeklyMealPlan, RAGMealComposition } from "../types/graphql";

/**
 * Generates an iCal (.ics) string from a WeeklyMealPlan
 */
export function generateICal(plan: WeeklyMealPlan): string {
    const DAYS = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"];

    const today = new Date();
    const dayOfWeek = today.getDay();
    const mondayOffset = (dayOfWeek === 0 ? -6 : 1 - dayOfWeek);
    const mondayDate = new Date(today);
    mondayDate.setDate(today.getDate() + mondayOffset);

    let ics = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//EaseMeals//Meal Planner//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH"
    ];

    DAYS.forEach((day, index) => {
        const currentDate = new Date(mondayDate);
        currentDate.setDate(mondayDate.getDate() + index);
        const dailyPlan = (plan as any)[day];
        if (!dailyPlan) return;
        ics.push(...generateEvent(currentDate, "080000", "090000", "Breakfast", dailyPlan.breakfast));
        ics.push(...generateEvent(currentDate, "130000", "140000", "Lunch", dailyPlan.lunch));
        ics.push(...generateEvent(currentDate, "190000", "200000", "Dinner", dailyPlan.dinner));
    });

    ics.push("END:VCALENDAR");
    return ics.join("\r\n");
}

function generateEvent(
    date: Date,
    startTime: string,
    endTime: string,
    mealType: string,
    composition: RAGMealComposition
): string[] {
    if (!composition) return [];
    const dateStr = date.toISOString().split('T')[0].replace(/-/g, '');
    const timestamp = new Date().toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
    const items = getMealItems(composition);
    const mealName = items.join(", ") || "Planned Meal";
    const summary = `EaseMeals: ${mealType} - ${mealName}`;
    const description = `Your planned ${mealType} for today.\n\nItems:\n- ${items.join("\n- ")}`;
    const uid = `easemeals-${dateStr}-${mealType.toLowerCase()}@easemeals.com`;
    return [
        "BEGIN:VEVENT",
        `UID:${uid}`,
        `DTSTAMP:${timestamp}`,
        `DTSTART:${dateStr}T${startTime}`,
        `DTEND:${dateStr}T${endTime}`,
        `SUMMARY:${summary}`,
        `DESCRIPTION:${description.replace(/\n/g, "\\n")}`,
        "END:VEVENT"
    ];
}

/**
 * Triggers a download of the iCal file
 */
export function downloadICal(icsContent: string, filename: string = "EaseMeals-Timetable.ics") {
    const blob = new Blob([icsContent], { type: "text/calendar;charset=utf-8" });
    const url = window.URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", filename);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
}

// --- Helpers ---

function getMealItems(composition: RAGMealComposition | null | undefined): string[] {
    if (!composition) return [];
    const items: string[] = [];
    if (composition.base) items.push(composition.base.name);
    if (composition.protein) items.push(composition.protein.name);
    if (composition.soup) items.push(composition.soup.name);
    if (composition.sides?.length) items.push(...composition.sides.filter(Boolean).map(s => s!.name));
    return items;
}

function getWeekDates(plan: WeeklyMealPlan): { day: string; date: Date }[] {
    const DAYS = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"];
    const today = new Date();
    const dayOfWeek = today.getDay();
    const mondayOffset = dayOfWeek === 0 ? -6 : 1 - dayOfWeek;
    const mondayDate = new Date(today);
    mondayDate.setDate(today.getDate() + mondayOffset);

    return DAYS.map((day, index) => {
        const d = new Date(mondayDate);
        d.setDate(mondayDate.getDate() + index);
        return { day, date: d };
    });
}

function buildDayDescription(dailyPlan: any): string {
    const breakfast = getMealItems(dailyPlan?.breakfast);
    const lunch = getMealItems(dailyPlan?.lunch);
    const dinner = getMealItems(dailyPlan?.dinner);
    return [
        `Breakfast: ${breakfast.length ? breakfast.join(", ") : "-"}`,
        `Lunch: ${lunch.length ? lunch.join(", ") : "-"}`,
        `Dinner: ${dinner.length ? dinner.join(", ") : "-"}`,
        "Generated by EaseMeals",
    ].join("\n");
}

/**
 * Generates Google Calendar deep-links — one per day (with all 3 meals in description)
 */
export function generateGoogleCalendarLinks(plan: WeeklyMealPlan): { day: string; url: string }[] {
    return getWeekDates(plan).map(({ day, date }) => {
        const dailyPlan = (plan as any)[day];
        const description = buildDayDescription(dailyPlan);
        const dateStr = date.toISOString().split('T')[0].replace(/-/g, '');
        const nextDay = new Date(date);
        nextDay.setDate(nextDay.getDate() + 1);
        const nextDateStr = nextDay.toISOString().split('T')[0].replace(/-/g, '');
        const label = day.charAt(0).toUpperCase() + day.slice(1);
        const params = new URLSearchParams({
            action: "TEMPLATE",
            text: `EaseMeals: ${label} Meal Plan`,
            dates: `${dateStr}/${nextDateStr}`,
            details: description,
            sf: "true",
            output: "xml",
        });
        return { day: label, url: `https://calendar.google.com/calendar/render?${params.toString()}` };
    });
}

/**
 * Generates Outlook Web deep-links — one per day
 */
export function generateOutlookLinks(plan: WeeklyMealPlan): { day: string; url: string }[] {
    return getWeekDates(plan).map(({ day, date }) => {
        const dailyPlan = (plan as any)[day];
        const body = buildDayDescription(dailyPlan);
        const startDt = date.toISOString().split('T')[0] + "T00:00:00";
        const nextDay = new Date(date);
        nextDay.setDate(nextDay.getDate() + 1);
        const endDt = nextDay.toISOString().split('T')[0] + "T00:00:00";
        const label = day.charAt(0).toUpperCase() + day.slice(1);
        const params = new URLSearchParams({
            subject: `EaseMeals: ${label} Meal Plan`,
            startdt: startDt,
            enddt: endDt,
            allday: "true",
            body,
        });
        return { day: label, url: `https://outlook.live.com/calendar/0/addevent?${params.toString()}` };
    });
}
